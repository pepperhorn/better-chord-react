// Generate src/verovio-fonts.generated.ts — embeds the bundled Verovio font
// zips as base64 so the notation renderer is self-contained (no runtime asset
// hosting), mirroring the woff2 embedding in src/staff-fonts.ts.
//
// Regenerate after rebuilding the zips: node scripts/embed-verovio-fonts.mjs
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const fontsDir = join(here, "..", "fonts", "verovio");
const out = join(here, "..", "src", "verovio-fonts.generated.ts");

async function b64(name) {
  return (await readFile(join(fontsDir, name))).toString("base64");
}

const bravura = await b64("Bravura.zip");
const petaluma = await b64("Petaluma.zip");

const header = `// AUTO-GENERATED by scripts/embed-verovio-fonts.mjs — do not edit by hand.
// Base64 of the bundled Verovio custom-font zips (packages/chordl-react/fonts/verovio).
// Loaded via Verovio's \`fontAddCustom\` option so the app engraves with the
// repo-bundled Bravura/Petaluma rather than whatever the Verovio build embeds.
/* eslint-disable */
`;

const body =
  header +
  `export const BRAVURA_ZIP_B64 = ${JSON.stringify(bravura)};\n` +
  `export const PETALUMA_ZIP_B64 = ${JSON.stringify(petaluma)};\n` +
  `export const VEROVIO_FONT_ZIPS: Record<string, string> = {\n` +
  `  Bravura: BRAVURA_ZIP_B64,\n` +
  `  Petaluma: PETALUMA_ZIP_B64,\n` +
  `};\n`;

await writeFile(out, body);
console.log(`wrote ${out} (${(body.length / 1024).toFixed(0)} KB)`);
